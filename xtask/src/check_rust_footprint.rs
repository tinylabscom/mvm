//! `xtask check-rust-footprint` — the declared, reproducible Rust-footprint
//! measurement, and a ratchet on it.
//!
//! Measurement: every Rust file tracked by git (`git ls-files '*.rs'`, so the
//! committed tree and nothing else), each assigned to exactly one category in
//! this priority order:
//!
//! 1. `vendored`: path under `third_party/`.
//! 2. `generated`: one of the generator marker comments in the first 12 lines.
//! 3. `tests`: a `tests` or `benches` directory segment.
//! 4. `first-party`: everything else. Inline `#[cfg(test)]` code stays here;
//!    it is not split out, so this category overstates production code.
//!
//! Two figures per category, reported separately and never merged:
//!
//! - physical lines: LF count, plus one for a final line without LF.
//! - SLOC: lines that still hold a non-whitespace character once comments
//!   (line, block and doc) are blanked. String literal bodies are kept, so a
//!   multi-line literal counts line by line.
//!
//! The ratchet: the SLOC and physical-line ceilings below are the last
//! accepted limits. The gate fails when either is exceeded and
//! also when the tree has fallen far enough under a ceiling that it should be
//! lowered, so a reduction is locked in rather than spent. No category is
//! excluded from the totals.
//!
//! The figures are measurements, not a verdict on any target: whether the
//! physical total or the SLOC total is the accepted measure is the
//! maintainers' call.

use anyhow::{Context, Result, bail};
use std::path::Path;
use std::process::Command;

use crate::rust_source::{CommentSyntax, blank_comments};

// The v2 composable pack's authenticated composition and pinned local/remote
// custody, including refusal tests, plus main's mailbox work measure 978,634
// SLOC / 1,249,056 physical lines. Keep both bounds tight without dropping
// a trust-boundary test; the prior v2 limits were 977,000 / 1,247,000.
/// Ceiling on total SLOC, all categories.
const MAX_TOTAL_SLOC: usize = 978_700;
/// Ceiling on total physical lines, all categories.
const MAX_TOTAL_PHYSICAL: usize = 1_249_100;
/// How far under a ceiling the tree may sit before the ceiling must drop.
const SLACK: usize = 10_000;

const GENERATED_MARKERS: &[&str] = &[
    "// @generated",
    "// This file is generated",
    "// Automatically generated",
    "/* automatically generated by rust-bindgen",
];

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Category {
    Vendored,
    Generated,
    Tests,
    FirstParty,
}

impl Category {
    const ALL: [Category; 4] = [
        Category::Vendored,
        Category::Generated,
        Category::Tests,
        Category::FirstParty,
    ];

    fn label(self) -> &'static str {
        match self {
            Category::Vendored => "vendored",
            Category::Generated => "generated",
            Category::Tests => "tests/benches",
            Category::FirstParty => "first-party",
        }
    }
}

#[derive(Default, Clone, Copy, Debug, PartialEq, Eq)]
struct Tally {
    files: usize,
    physical: usize,
    sloc: usize,
}

fn classify(path: &str, source: &str) -> Category {
    if path.starts_with("third_party/") {
        return Category::Vendored;
    }
    if source
        .lines()
        .take(12)
        .any(|l| GENERATED_MARKERS.iter().any(|m| l.starts_with(m)))
    {
        return Category::Generated;
    }
    if path.split('/').any(|s| s == "tests" || s == "benches") {
        return Category::Tests;
    }
    Category::FirstParty
}

fn physical_lines(source: &str) -> usize {
    source.bytes().filter(|&b| b == b'\n').count()
        + usize::from(!source.is_empty() && !source.ends_with('\n'))
}

fn sloc(source: &str) -> usize {
    blank_comments(source, CommentSyntax::Rust)
        .lines()
        .filter(|l| !l.trim().is_empty())
        .count()
}

fn measure<'a>(files: impl IntoIterator<Item = (&'a str, &'a str)>) -> [Tally; 4] {
    let mut out = [Tally::default(); 4];
    for (path, source) in files {
        let i = Category::ALL
            .iter()
            .position(|c| *c == classify(path, source))
            .unwrap_or(3);
        out[i].files += 1;
        out[i].physical += physical_lines(source);
        out[i].sloc += sloc(source);
    }
    out
}

fn verdict(total: Tally) -> Result<()> {
    for (name, got, max) in [
        ("SLOC", total.sloc, MAX_TOTAL_SLOC),
        ("physical lines", total.physical, MAX_TOTAL_PHYSICAL),
    ] {
        if got > max {
            bail!(
                "total {name} {got} exceeds the ceiling {max}; delete code or justify raising it"
            );
        }
        if got + SLACK < max {
            bail!(
                "total {name} {got} is more than {SLACK} under the ceiling {max}; lower the ceiling in check_rust_footprint.rs to lock the reduction in"
            );
        }
    }
    Ok(())
}

pub(crate) fn run(workspace: &Path) -> Result<()> {
    let listing = Command::new("git")
        .args(["ls-files", "-z", "*.rs"])
        .current_dir(workspace)
        .output()
        .context("run git ls-files")?;
    if !listing.status.success() {
        bail!("git ls-files failed");
    }
    let mut sources = Vec::new();
    for path in String::from_utf8(listing.stdout)?
        .split('\0')
        .filter(|p| !p.is_empty())
    {
        let source = std::fs::read_to_string(workspace.join(path))
            .with_context(|| format!("read {path}"))?;
        sources.push((path.to_owned(), source));
    }
    let tallies = measure(sources.iter().map(|(p, s)| (p.as_str(), s.as_str())));

    let mut total = Tally::default();
    println!(
        "{:<14} {:>6} {:>10} {:>10}",
        "category", "files", "physical", "SLOC"
    );
    for (c, t) in Category::ALL.iter().zip(tallies) {
        println!(
            "{:<14} {:>6} {:>10} {:>10}",
            c.label(),
            t.files,
            t.physical,
            t.sloc
        );
        total.files += t.files;
        total.physical += t.physical;
        total.sloc += t.sloc;
    }
    println!(
        "{:<14} {:>6} {:>10} {:>10}",
        "total", total.files, total.physical, total.sloc
    );
    verdict(total)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn categories_follow_the_priority_order() {
        assert_eq!(classify("third_party/x/tests/a.rs", ""), Category::Vendored);
        assert_eq!(
            classify("crates/a/tests/a.rs", "// @generated\n"),
            Category::Generated
        );
        assert_eq!(classify("crates/a/benches/a.rs", ""), Category::Tests);
        assert_eq!(
            classify("crates/a/src/a.rs", "fn a() {}\n"),
            Category::FirstParty
        );
    }

    #[test]
    fn physical_and_sloc_are_counted_distinctly() {
        let src = "// c\n\n/* b\nb */\nfn a() {}\n/// d\nlet s = \"x\ny\";";
        assert_eq!(physical_lines(src), 8);
        assert_eq!(sloc(src), 3);
        assert_eq!(physical_lines(""), 0);
    }

    #[test]
    fn a_tree_over_or_far_under_a_ceiling_fails() {
        let at = Tally {
            files: 1,
            physical: MAX_TOTAL_PHYSICAL,
            sloc: MAX_TOTAL_SLOC,
        };
        verdict(at).expect("at the ceiling passes");
        let over = Tally {
            sloc: MAX_TOTAL_SLOC + 1,
            ..at
        };
        assert!(verdict(over).is_err());
        let under = Tally {
            sloc: MAX_TOTAL_SLOC - SLACK - 1,
            ..at
        };
        assert!(verdict(under).is_err());
    }
}
