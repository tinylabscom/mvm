//! Emit the SDK environment-variable registry as a JSON manifest.
//!
//! Unlike its sibling `emit_*_schema` bins this writes a JSON
//! **instance**, not a JSON Schema. The distinction matters: a
//! constant is a value, and neither downstream generator can emit one.
//! `json-schema-to-typescript` produces `export type` declarations,
//! which `tsc` erases — so a "generated" constant would be invisible to
//! the s27 surface check that reads `Object.keys(mvm)` at runtime, and
//! the drift gate would certify a binding that does not exist. The
//! per-language rendering therefore lives in
//! `xtask/src/gen_sdk_surface.rs` instead, and this bin's only job is
//! to hand it the registry.
//!
//! Needs no `schema` feature: `serde_json` is an unconditional
//! dependency of this crate and `schemars` is not involved.

use mvm_sdk::env::{REGISTRY, Surface};
use serde_json::{Map, Value, json};

const SURFACES: [Surface; 3] = [Surface::Rust, Surface::Python, Surface::TypeScript];

fn main() {
    let vars: Vec<Value> = REGISTRY
        .iter()
        .map(|v| {
            let surfaces: Vec<Value> = SURFACES
                .iter()
                .filter(|s| v.exports_to(**s))
                .map(|s| Value::from(s.as_str()))
                .collect();
            json!({
                "ident": v.ident,
                "name": v.name,
                "doc": v.doc.trim(),
                "surfaces": surfaces,
            })
        })
        .collect();

    let mut root = Map::new();
    root.insert(
        "_comment".into(),
        json!([
            "Generated by `cargo xtask gen-stubs` from crates/mvm-sdk/src/env.rs.",
            "This is a JSON instance document, NOT a JSON Schema — it carries",
            "values, and the per-language bindings are rendered from it by",
            "xtask/src/gen_sdk_surface.rs rather than by the schema generators.",
            "Do not edit by hand; `cargo xtask check-stubs` fails on drift.",
            "A name lists a surface only when that surface actually reads it."
        ]),
    );
    root.insert("version".into(), json!(0));
    root.insert("vars".into(), Value::Array(vars));

    println!(
        "{}",
        serde_json::to_string_pretty(&Value::Object(root)).expect("serialize env registry")
    );
}
