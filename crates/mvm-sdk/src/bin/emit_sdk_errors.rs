//! Emit the SDK error taxonomy as a JSON manifest.
//!
//! A JSON **instance**, not a JSON Schema — same reasoning as
//! `emit_sdk_env`: the downstream schema generators emit type
//! declarations, and a class with a base, a docstring and a status
//! mapping is not expressible as one. The per-language rendering lives
//! in `xtask/src/gen_sdk_surface.rs`.
//!
//! Per-language base names are resolved here rather than in the
//! emitter, so the mapping from "what this extends conceptually" to
//! "what it extends in Python / TypeScript" stays in Rust with the
//! registry that defines it.

use mvm_sdk::env::Surface;
use mvm_sdk::error_taxonomy::all;
use serde_json::{Map, Value, json};

const SURFACES: [Surface; 3] = [Surface::Rust, Surface::Python, Surface::TypeScript];

fn main() {
    let errors: Vec<Value> = all()
        .map(|e| {
            let surfaces: Vec<Value> = SURFACES
                .iter()
                .filter(|s| e.exports_to(**s))
                .map(|s| Value::from(s.as_str()))
                .collect();
            json!({
                "name": e.name,
                "base_python": e.base.python(),
                "base_typescript": e.base.typescript(),
                "doc": e.doc.trim(),
                "status": e.status,
                "surfaces": surfaces,
                "fields": e.fields.iter().map(|f| json!({
                    "name": f.name, "doc": f.doc,
                })).collect::<Vec<_>>(),
                "message_format": e.message_format,
            })
        })
        .collect();

    let mut root = Map::new();
    root.insert(
        "_comment".into(),
        json!([
            "Generated by `cargo xtask gen-stubs` from",
            "crates/mvm-sdk/src/error_taxonomy.rs.",
            "A JSON instance document, NOT a JSON Schema: it carries class",
            "names, base classes and status codes, which the schema generators",
            "cannot express. Rendered by xtask/src/gen_sdk_surface.rs.",
            "Do not edit by hand; `cargo xtask check-stubs` fails on drift.",
            "Order is significant — a base class precedes its subclasses.",
            "A type lists a surface only when that surface can express it and",
            "has code that raises it."
        ]),
    );
    // `OK` is not an error type, so it has no registry row — but it is
    // part of the same `MVM_HSVC_*` family the SDKs were mirroring by
    // hand, and leaving it behind would leave the mirror half-alive.
    root.insert(
        "status_ok".into(),
        json!(mvm_sdk::error_taxonomy::STATUS_OK),
    );
    root.insert("version".into(), json!(0));
    root.insert("errors".into(), Value::Array(errors));

    println!(
        "{}",
        serde_json::to_string_pretty(&Value::Object(root)).expect("serialize error taxonomy")
    );
}
