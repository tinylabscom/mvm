//! Emit the SDK constructor registry as a JSON manifest.
//!
//! A JSON instance, not a JSON Schema — a constructor with defaults,
//! constraints and a target variant is not a type, and the pinned schema
//! generators emit only types. Rendered by
//! `xtask/src/gen_sdk_surface.rs`.

use mvm_sdk::ctor_registry::{Constraint, Ctor, FieldValue, Literal, ParamType, REGISTRY, Target};
use mvm_sdk::env::Surface;
use serde_json::{Map, Value, json};

const SURFACES: [Surface; 3] = [Surface::Rust, Surface::Python, Surface::TypeScript];

fn param_type(ty: ParamType) -> Value {
    match ty {
        ParamType::Str => json!({"kind": "str"}),
        ParamType::Int => json!({"kind": "int"}),
        ParamType::ListOf(item) => json!({"kind": "list", "item": item}),
    }
}

fn literal(value: Literal) -> Value {
    match value {
        Literal::Int(v) => json!({"kind": "int", "value": v}),
        Literal::Str(v) => json!({"kind": "str", "value": v}),
        Literal::Null => json!({"kind": "null"}),
    }
}

fn constraint(c: &Constraint) -> Value {
    match c {
        Constraint::NonEmpty { message } => json!({"kind": "non_empty", "message": message}),
        Constraint::IntExclusiveRange { min, max, message } => json!({
            "kind": "int_exclusive_range", "min": min, "max": max, "message": message,
        }),
        Constraint::EnumMember {
            canonical,
            aliases,
            message,
        } => json!({
            "kind": "enum_member",
            "canonical": canonical,
            "aliases": aliases
                .iter()
                .map(|(a, c)| json!({"from": a, "to": c}))
                .collect::<Vec<_>>(),
            "message": message,
        }),
    }
}

fn field_value(v: &FieldValue) -> Value {
    match v {
        FieldValue::Param(p) => json!({"kind": "param", "param": p}),
        FieldValue::ParamList(p) => json!({"kind": "param_list", "param": p}),
        FieldValue::ParamEnum { param, enum_type } => {
            json!({"kind": "param_enum", "param": param, "enum_type": enum_type})
        }
    }
}

fn target(t: &Target) -> Value {
    match t {
        Target::Struct { name } => json!({"kind": "struct", "name": name}),
        Target::Variant {
            union,
            discriminant,
        } => json!({"kind": "variant", "union": union, "discriminant": discriminant}),
    }
}

fn ctor(c: &Ctor) -> Value {
    json!({
        "name": c.name,
        "doc": c.doc.split_whitespace().collect::<Vec<_>>().join(" "),
        "params": c.params.iter().map(|p| json!({
            "name": p.name,
            "type": param_type(p.ty),
            "default": p.default.map(literal),
            "kw_only": p.kw_only,
            "constraints": p.constraints.iter().map(constraint).collect::<Vec<_>>(),
        })).collect::<Vec<_>>(),
        "target": target(&c.target),
        "fields": c.fields.iter().map(|(name, value)| json!({
            "name": name, "value": field_value(value),
        })).collect::<Vec<_>>(),
        "surfaces": SURFACES
            .iter()
            .filter(|s| c.exports_to(**s))
            .map(|s| Value::from(s.as_str()))
            .collect::<Vec<_>>(),
    })
}

fn main() {
    let mut root = Map::new();
    root.insert(
        "_comment".into(),
        json!([
            "Generated by `cargo xtask gen-stubs` from",
            "crates/mvm-sdk/src/ctor_registry.rs.",
            "A JSON instance document, NOT a JSON Schema: it carries parameter",
            "defaults, runtime constraints and target variants, none of which a",
            "schema can express. Rendered by xtask/src/gen_sdk_surface.rs.",
            "Do not edit by hand; `cargo xtask check-stubs` fails on drift.",
            "Constraints are what the dynamic SDKs must check at runtime and",
            "Rust discharges through its type system — which is why they are",
            "declared here rather than extracted from crates/mvm-sdk/src/ctor/."
        ]),
    );
    root.insert("version".into(), json!(0));
    root.insert(
        "ctors".into(),
        Value::Array(REGISTRY.iter().map(ctor).collect()),
    );

    println!(
        "{}",
        serde_json::to_string_pretty(&Value::Object(root)).expect("serialize ctor registry")
    );
}
