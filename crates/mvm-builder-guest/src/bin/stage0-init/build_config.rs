use std::collections::HashMap;
use std::path::{Path, PathBuf};

const BUILD_CONFIG_NAME: &str = "stage0-build.conf";

/// Prefer the config carried on the input disk, retaining the shared-output
/// path for the QEMU transport.
pub(super) fn locate(input_stage: &Path, shared_output_config: &Path) -> PathBuf {
    let staged = input_stage.join("conf").join(BUILD_CONFIG_NAME);
    if staged.exists() {
        staged
    } else {
        shared_output_config.to_path_buf()
    }
}

/// Read the host's small, token-validated set of `MVM_STAGE0_*` assignments.
pub(super) fn read(path: &Path) -> HashMap<String, String> {
    let mut values = HashMap::new();
    let Ok(text) = std::fs::read_to_string(path) else {
        return values;
    };
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some((key, value)) = line.split_once('=') {
            let value = value.trim().trim_matches('"').trim_matches('\'');
            values.insert(key.trim().to_string(), value.to_string());
        }
    }
    values
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn locate_prefers_the_input_disk_config() {
        let scratch = tempfile::TempDir::new().unwrap();
        let input_stage = scratch.path().join("input");
        let staged = input_stage.join("conf").join(BUILD_CONFIG_NAME);
        std::fs::create_dir_all(staged.parent().unwrap()).unwrap();
        std::fs::write(&staged, "MVM_STAGE0_OUTPUT_MODE=kernel\n").unwrap();

        assert_eq!(
            locate(&input_stage, scratch.path().join("shared.conf").as_path()),
            staged
        );
    }

    #[test]
    fn locate_falls_back_when_the_input_disk_has_no_config() {
        let scratch = tempfile::TempDir::new().unwrap();
        let shared = scratch.path().join("shared.conf");

        assert_eq!(locate(&scratch.path().join("input"), &shared), shared);
    }

    #[test]
    fn read_accepts_plain_and_quoted_assignments() {
        let scratch = tempfile::TempDir::new().unwrap();
        let path = scratch.path().join(BUILD_CONFIG_NAME);
        std::fs::write(
            &path,
            "# generated by the host\nMVM_STAGE0_BUILD_ATTR=kernel\n\
             MVM_STAGE0_OUTPUT_MODE='kernel'\n",
        )
        .unwrap();

        let values = read(&path);
        assert_eq!(values.get("MVM_STAGE0_BUILD_ATTR").unwrap(), "kernel");
        assert_eq!(values.get("MVM_STAGE0_OUTPUT_MODE").unwrap(), "kernel");
    }

    #[test]
    fn read_returns_empty_for_an_absent_config() {
        let scratch = tempfile::TempDir::new().unwrap();
        assert!(read(&scratch.path().join("absent.conf")).is_empty());
    }
}
